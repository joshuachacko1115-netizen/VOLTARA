def detect_dataset(df: pd.DataFrame) -> str:
    cols = {str(c).strip() for c in df.columns}
    for key, meta in EV_DATASETS.items():
        ids = {c for c in meta["signature"] if "id" in c.lower()}
        if ids <= cols:
            return key
    raise ValueError("Unrecognised CSV: expected the ev_degradation format (battery_id, observation_id, ...) "
                     "or the ev_telematics format (Vehicle_ID, Trip_ID, ...). Download a sample to see the columns.")


def detect_dataset_safe(df: pd.DataFrame) -> str | None:
    try:
        return detect_dataset(df)
    except ValueError:
        return None


def _trend(age_years: pd.Series, soh: pd.Series) -> tuple | None:
    ok = age_years.notna() & soh.notna()
    if ok.sum() < 3 or np.ptp(age_years[ok]) < 0.25:
        return None
    slope = np.polyfit(age_years[ok], soh[ok], 1)[0]
    return float(soh[ok].iloc[0]), float(soh[ok].iloc[-1]), float(np.ptp(age_years[ok])), float(-slope)


def assess_history(raw: pd.DataFrame, soc_pct: float | None = None, consumption_kwh_100km: float | None = None,
                   source: str = "history CSV") -> Assessment:
    """Assess the LAST row of one battery's / vehicle's history (earlier rows feed the trend)."""
    dataset = detect_dataset(raw)
    unit = raw_unit_column(dataset)
    if raw[unit].nunique() != 1:
        raise ValueError(f"The CSV must contain one {unit}; found {raw[unit].nunique()}.")
    model = EVPredictor(dataset)
    pred, feats = model.predict(raw), model.prepare(raw)
    if dataset == "ev_degradation":
        return _assess_degradation(raw, pred, feats, soc_pct, consumption_kwh_100km, source)
    return _assess_telematics(pred, feats, soc_pct, consumption_kwh_100km, source)


def _assess_degradation(raw, pred, feats, soc_pct, consumption, source) -> Assessment:
    last = feats.iloc[-1]
    soh = float(pred.pred_degradation_soh.iloc[-1])
    rul = 0.0 if soh <= EV_EOL_SOH_PCT else max(float(pred.pred_degradation_rul.iloc[-1]), 0.0)
    years = rul_years(rul, last.efc, last.battery_age_days)
    soc = float(last.avg_state_of_charge_pct) if soc_pct is None and pd.notna(last.avg_state_of_charge_pct) else soc_pct
    consumption = consumption or VEHICLE_TYPES["Electric car"]["consumption_kwh_100km"]
    rng, full = range_km(last.pack_capacity_kwh, soh, soc or 80.0, consumption)
    a = Assessment(source, soh, model_error("degradation_soh"), rng, full, rul, years, model_error("degradation_rul"),
                   risk=str(pred.pred_degradation_risk.iloc[-1]))
    a.soh_interval = interval(model_meta("degradation_soh"), soh, rul=False)
    a.rul_interval = interval(model_meta("degradation_rul"), rul, rul=True) if soh > EV_EOL_SOH_PCT else None
    if "state_of_health_pct" in raw and raw.state_of_health_pct.notna().any():
        a.soh_measured_pct = float(feats.state_of_health_pct.iloc[-1])
    # Anomalies: statistical outlier flags + rule checks, on every row; the latest are listed first.
    masker = load_masker()
    found = []
    if masker is not None:
        clean, _ = clean_ev_degradation(raw.assign(**{c: pd.to_datetime(raw[c]) for c in
                                                      ("manufacture_date", "observation_date", "last_service_date")
                                                      if c in raw}), masker, require_targets=False)
        for c in masker.columns:
            for i in np.flatnonzero(clean[f"flag_outlier_{c}"].to_numpy()):
                found.append((i, f"{c.replace('_', ' ')} = {raw_value(feats, i, c)} is unusual for this battery "
                                 f"(observation {feats.observation_id.iloc[i]})"))
    for i in np.flatnonzero(feats.peak_temp_during_fast_charge_c > PEAK_CHARGE_TEMP_C):
        found.append((i, f"fast-charge peak temperature {feats.peak_temp_during_fast_charge_c.iloc[i]:.1f} °C "
                         f"> {PEAK_CHARGE_TEMP_C:g} °C (observation {feats.observation_id.iloc[i]})"))
    for i in np.flatnonzero(feats.r_growth > R_GROWTH):
        found.append((i, f"internal resistance {100 * (feats.r_growth.iloc[i] - 1):.0f} % above its first readings "
                         f"(observation {feats.observation_id.iloc[i]})"))
    drops = -pred.pred_degradation_soh.diff()
    for i in np.flatnonzero(drops > SOH_DROP_PTS):
        found.append((i, f"predicted SoH dropped {drops.iloc[i]:.1f} points since the previous observation "
                         f"({feats.observation_id.iloc[i]})"))
    a.anomalies = [m for _, m in sorted(found, key=lambda t: -t[0])]
    hist = pd.DataFrame({"age_years": feats.battery_age_days / 365.25, "soh_pred": pred.pred_degradation_soh,
                         "rul_pred": pred.pred_degradation_rul.clip(lower=0), "risk": pred.pred_degradation_risk})
    if "state_of_health_pct" in feats and feats.state_of_health_pct.notna().any():
        hist["soh_measured"] = feats.state_of_health_pct.to_numpy()
    a.history = hist
    out_of_range = pred.inputs_outside_training_range.iloc[-1]
    if out_of_range:
        a.warnings.append(f"Latest row has values outside the training range: {out_of_range}.")
    a.insights = build_insights(
        a, trend=_trend(hist.age_years, hist.soh_pred), consumption=consumption, soc=soc or 80.0,
        usage={"age_years": last.battery_age_days / 365.25, "fast_charge_ratio": last.fast_charge_ratio_hist_mean,
               "avg_soc": last.avg_state_of_charge_pct_hist_mean,
               "hot": bool((feats.peak_temp_during_fast_charge_c > PEAK_CHARGE_TEMP_C).any())})
    a.notes = {"dataset": "ev_degradation", "rows": len(feats), "unit": str(last.battery_id),
               "equivalent_full_cycles": float(last.efc) if pd.notna(last.efc) else None}
    return a


def raw_value(feats: pd.DataFrame, i: int, c: str) -> str:
    v = feats[c].iloc[i]
    return "missing" if pd.isna(v) else f"{v:.1f}"


def _assess_telematics(pred, feats, soc_pct, consumption, source) -> Assessment:
    last = feats.iloc[-1]
    soh = float(pred.pred_telematics_soh.iloc[-1])
    efc, age_days = float(last.battery_cycles), float(last.vehicle_age_years) * 365.25
    # No RUL label in this dataset: the manual-entry RUL model (trained on ev_degradation) is used.
    models = load_quick_models()
    X = quick_features(age_days, efc, last.battery_type, None)
    _, rul = predict_quick(models, X)
    rul = 0.0 if soh <= EV_EOL_SOH_PCT else float(rul[0])
    years = rul_years(rul, efc, age_days)
    soc = float(last.soc_pct) if soc_pct is None else soc_pct
    used = consumption or float(last.wh_per_km) / 10           # Wh/km -> kWh/100 km
    rng, full = range_km(last.battery_capacity_kwh, soh, soc, used)
    a = Assessment(source, soh, model_error("telematics_soh"), rng, full, rul, years, model_error("quick_rul"),
                   risk=risk_from(soh, years))
    a.soh_interval = interval(model_meta("telematics_soh"), soh, rul=False)
    a.rul_interval = (interval(models["quick_rul"]["meta"], rul, rul=True, unknown=pd.isna(last.battery_type))
                      if soh > EV_EOL_SOH_PCT else None)
    if "soh_pct" in feats:
        a.soh_measured_pct = float(feats.soh_pct.iloc[-1])
    found = []
    for i in range(len(feats)):
        r = feats.iloc[i]
        if r.battery_temp_c > BATTERY_TEMP_C:
            found.append((i, f"battery temperature {r.battery_temp_c:.1f} °C > {BATTERY_TEMP_C:g} °C on {r.trip_id}"))
        if r.batt_temp_rise_c > TEMP_RISE_C:
            found.append((i, f"battery {r.batt_temp_rise_c:.1f} °C above ambient on {r.trip_id}"))
        nominal = NOMINAL_V.get(r.battery_type)
        if nominal and abs(r.battery_voltage_v / nominal - 1) > VOLTAGE_BAND:
            found.append((i, f"pack voltage {r.battery_voltage_v:.0f} V is more than {VOLTAGE_BAND:.0%} from the "
                             f"{r.battery_type} nominal {nominal:.0f} V on {r.trip_id}"))
    a.anomalies = [m for _, m in sorted(found, key=lambda t: -t[0])]
    p_fail = 1 - pred["p_telematics_failure_type_Normal"].iloc[-1]
    a.notes = {"dataset": "ev_telematics", "rows": len(feats), "unit": str(last.vehicle_id),
               "rul_note": "This dataset has no RUL labels; RUL comes from the manual-entry model trained on "
                           "ev_degradation, using the vehicle's cycle count and age.",
               "p_failure_any": float(p_fail),
               "p_maintenance": float(pred["p_telematics_maintenance_Yes"].iloc[-1]),
               "equivalent_full_cycles": efc}
    hist = pd.DataFrame({"age_years": feats.vehicle_age_years, "soh_pred": pred.pred_telematics_soh})
    if "soh_pct" in feats:
        hist["soh_measured"] = feats.soh_pct.to_numpy()
    a.history = hist
    a.insights = build_insights(
        a, trend=_trend(hist.age_years, hist.soh_pred), consumption=used, soc=soc,
        usage={"age_years": float(last.vehicle_age_years), "fast_charge_ratio": float(last.dc_fast_charge_hist_mean),
               "hot": bool((feats.battery_temp_c > BATTERY_TEMP_C).any())})
    return a



# Samples (held-out test units, never used for training)
# --------------------------------------------------------------------------- #
def sample_units(dataset: str, min_rows: int = 3, limit: int = 60) -> list[str]:
    split = pd.read_csv(REPORTS_DIR / "results" / "ev_split_units.csv")
    test = set(split[(split.dataset == dataset) & (split.split == "test")].unit)
    raw = pd.read_csv(find_ev_files()[dataset], usecols=[0])
    counts = raw.iloc[:, 0].value_counts()
    units = sorted(u for u in test if counts.get(u, 0) >= min_rows)
    return units[:limit]


def sample_history(dataset: str, unit: str) -> pd.DataFrame:
    raw = pd.read_csv(find_ev_files()[dataset])
    return raw[raw[raw_unit_column(dataset)] == unit].reset_index(drop=True)


def raw_unit_column(dataset: str) -> str:
    return "battery_id" if dataset == "ev_degradation" else "Vehicle_ID"

"""Vehicle assessment for the dashboard's EV page: SoH, range, RUL, anomalies, insights.

Three input routes, all ending in the same `Assessment`:
  * manual entry   six numbers a driver knows (capacity, SoC, age, odometer,
                   consumption, vehicle type) -> the "quick" models (ev_quick_*), which
                   use age and equivalent full cycles = odometer x consumption / capacity
  * history CSV    rows in either EV dataset's original format -> EVPredictor (full models)
  * sample         a held-out battery / vehicle from the data, same as the CSV route

What is measured, modelled or assumed is kept apart:
  * SoH and RUL are model outputs, with the model's error on held-out batteries and a
    90 % prediction interval (split-conformal, src/models/ev_intervals.py);
  * range = capacity x SoH x SoC / consumption: arithmetic on the stated consumption,
    not a validated range model;
  * anomalies are rule checks with stated thresholds (project choices) plus the
    statistical outlier flags of src/preprocessing/ev_cleaning.OutlierMasker;
  * insights are sentences generated by fixed rules from the numbers above (no language model).
"""

# Typical pack size and consumption per vehicle type (defaults for the form only).
VEHICLE_TYPES = {
    "Electric car": {"capacity_kwh": 60.0, "consumption_kwh_100km": 17.0, "in_training_data": True},
    "Electric scooter": {"capacity_kwh": 3.0, "consumption_kwh_100km": 3.5, "in_training_data": False},
    "Electric bus": {"capacity_kwh": 350.0, "consumption_kwh_100km": 120.0, "in_training_data": False},
}
CHEMISTRIES = ["Unknown", "NMC", "LFP", "NCA", "LMO"]
CLIMATES = ["Unknown", "temperate", "mixed", "cold", "hot_arid", "tropical_humid"]

# Rule thresholds (project choices, from the data distributions; README EV section).
PEAK_CHARGE_TEMP_C = 55.0      # ev_degradation peak fast-charge temperature, ~99th percentile
BATTERY_TEMP_C = 45.0          # ev_telematics pack temperature, between 99th and 99.9th percentile
TEMP_RISE_C = 8.0              # ev_telematics pack minus ambient, above the 99.9th percentile
NOMINAL_V = {"NMC": 390.0, "LFP": 355.0}   # dataset documentation
VOLTAGE_BAND = 0.05
SOH_DROP_PTS = 3.0             # predicted SoH falling this much between consecutive rows
R_GROWTH = 1.5                 # internal resistance 50 % above the battery's first readings
SOH_WATCH_PCT = 85.0


@dataclass
class ManualInput:
    vehicle_type: str = "Electric car"
    capacity_kwh: float = 60.0
    soc_pct: float = 80.0
    age_years: float = 3.0
    odometer_km: float = 45000.0
    consumption_kwh_100km: float = 17.0
    chemistry: str = "Unknown"
    climate: str = "Unknown"


@dataclass
class Assessment:
    source: str
    soh_pct: float | None
    soh_error_pct: float | None          # model MAE on held-out batteries
    range_km: float | None
    full_range_km: float | None
    rul_cycles: float | None
    rul_years: float | None
    rul_error_cycles: float | None
    anomalies: list[str] = field(default_factory=list)
    anomaly_assessed: bool = True
    warnings: list[str] = field(default_factory=list)
    insights: list[str] = field(default_factory=list)
    risk: str | None = None
    history: pd.DataFrame | None = None  # per-row predictions (history routes)
    soh_measured_pct: float | None = None
    notes: dict = field(default_factory=dict)
    soh_interval: tuple[float, float] | None = None   # 90 % prediction interval
    rul_interval: tuple[float, float] | None = None



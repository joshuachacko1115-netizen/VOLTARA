def validate_manual(inp: ManualInput) -> list[str]:
    errors = []
    for name, v, lo, hi in [("Battery capacity", inp.capacity_kwh, 0.5, 1000), ("Vehicle age", inp.age_years, 0, 40),
                            ("Odometer", inp.odometer_km, 0, 3_000_000),
                            ("Energy consumption", inp.consumption_kwh_100km, 1, 400), ("Charge", inp.soc_pct, 0, 100)]:
        if v is None or not np.isfinite(v) or not lo <= v <= hi:
            errors.append(f"{name} must be between {lo:g} and {hi:g}.")
    return errors


def assess_manual(inp: ManualInput, models: dict | None = None) -> Assessment:
    errors = validate_manual(inp)
    if errors:
        raise ValueError(" ".join(errors))
    models = models or load_quick_models()
    age_days = inp.age_years * 365.25
    efc = inp.odometer_km * inp.consumption_kwh_100km / 100 / inp.capacity_kwh
    X = quick_features(age_days, efc, inp.chemistry, inp.climate)
    soh, rul = predict_quick(models, X)
    soh, rul = float(soh[0]), float(rul[0])
    meta, rul_meta = models["quick_soh"]["meta"], models["quick_rul"]["meta"]
    known = inp.chemistry != "Unknown"
    scores = lambda m: m["test_scores"] if known else m.get("test_scores_categories_unknown", m["test_scores"])
    # Without the chemistry the RUL model barely beats a constant on held-out batteries
    # (README): withhold it rather than show a number that is mostly noise.
    rul_ok = known or scores(rul_meta)["R2"] >= 0.5
    rul = rul if rul_ok else None
    years = rul_years(rul, efc, age_days)
    rng, full = range_km(inp.capacity_kwh, soh, inp.soc_pct, inp.consumption_kwh_100km)
    a = Assessment("manual entry", soh, scores(meta)["MAE"], rng, full, rul, years,
                   scores(rul_meta)["MAE"], anomaly_assessed=False, risk=risk_from(soh, years))
    a.notes = {"equivalent_full_cycles": efc, "age_days": age_days}
    a.soh_interval = interval(meta, soh, rul=False, unknown=not known)
    a.rul_interval = interval(rul_meta, rul, rul=True) if rul and soh > EV_EOL_SOH_PCT else None
    w = a.warnings
    if not VEHICLE_TYPES.get(inp.vehicle_type, {}).get("in_training_data", True):
        w.append(f"The models were trained on car and van packs (40-100 kWh). For an {inp.vehicle_type.lower()} "
                 "the SoH and RUL are an extrapolation.")
    lo, hi = meta["feature_ranges"]["efc"]
    if not lo <= efc <= hi:
        w.append(f"{efc:.0f} equivalent full cycles is outside the training range ({lo:.0f}-{hi:.0f}).")
    lo, hi = meta["feature_ranges"]["battery_age_days"]
    if not lo <= age_days <= hi:
        w.append(f"An age of {inp.age_years:g} years is outside the training range "
                 f"({lo / 365.25:.1f}-{hi / 365.25:.1f} years).")
    km_per_day = inp.odometer_km / max(age_days, 1)
    if km_per_day > 500:
        w.append(f"{km_per_day:.0f} km per day on average looks implausible; check the odometer and age.")
    if not known:
        u = scores(rul_meta)
        w.append(f"Chemistry unknown: SOH averages over chemistries (typical error ±{scores(meta)['MAE']:.1f} "
                 f"points instead of ±{meta['test_scores']['MAE']:.1f}). RUL is not shown: without the chemistry "
                 f"its error on held-out batteries is ±{u['MAE']:.0f} cycles (R² {u['R2']:.2f}).")
    a.anomalies = []
    a.insights = build_insights(a, trend=None, consumption=inp.consumption_kwh_100km, soc=inp.soc_pct,
                                usage={"age_years": inp.age_years})
    return a



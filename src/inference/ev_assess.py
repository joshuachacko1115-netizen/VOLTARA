# Shared pieces
# --------------------------------------------------------------------------- #
def range_km(capacity_kwh, soh_pct, soc_pct, consumption_kwh_100km) -> tuple[float | None, float | None]:
    """(range at the current SoC, range on a full charge) under the stated consumption."""
    if not consumption_kwh_100km or consumption_kwh_100km <= 0 or not capacity_kwh or soh_pct is None:
        return None, None
    full = capacity_kwh * soh_pct / 100 / consumption_kwh_100km * 100
    return full * soc_pct / 100, full


def rul_years(rul_cycles: float | None, efc: float, age_days: float) -> float | None:
    """Remaining cycles turned into time at the battery's average cycling rate so far."""
    if rul_cycles is None or not age_days or age_days <= 0 or not efc or efc <= 0:
        return None
    return float(rul_cycles / (efc / (age_days / 365.25)))


def risk_from(soh: float | None, rul_years_: float | None) -> str | None:
    """Same thresholds as the NASA rule (README): High at <= 83 % SoH; Low above 90 %."""
    if soh is None:
        return None
    if soh <= EV_EOL_SOH_PCT + 3 or (rul_years_ is not None and rul_years_ < 1):
        return "High"
    if soh > 90 and (rul_years_ is None or rul_years_ > 3):
        return "Low"
    return "Medium"


def build_insights(a: Assessment, *, trend: tuple | None, consumption: float | None, soc: float | None,
                   usage: dict) -> list[str]:
    out = []
    if trend is not None:
        first, last, years, rate = trend
        msg = (f"Degradation trend: SoH went from {first:.1f} % to {last:.1f} % over {years:.1f} years "
               f"(about {rate:.1f} points per year).")
        if rate > 0 and a.soh_pct is not None and a.soh_pct > EV_EOL_SOH_PCT:
            msg += f" At that rate 80 % is reached in about {(a.soh_pct - EV_EOL_SOH_PCT) / rate:.1f} years."
        out.append(msg)
    elif a.soh_pct is not None and usage.get("age_years"):
        rate = (100 - a.soh_pct) / max(usage["age_years"], 0.1)
        why = ("the history covers too little time for a trend over recent cycles" if a.history is not None
               else "one reading: a trend over recent cycles needs a history upload")
        out.append(f"Degradation so far: about {rate:.1f} SoH points per year on average since new ({why}).")
    if a.anomalies:
        out.append(f"Abnormal behaviour: {len(a.anomalies)} finding(s), e.g. {a.anomalies[0]}.")
    elif a.anomaly_assessed:
        out.append("No abnormal voltage, temperature or resistance behaviour in the available readings.")
    if a.range_km is not None:
        out.append(f"Range: about {a.range_km:.0f} km at {soc:.0f} % charge and {consumption:g} kWh/100 km; "
                   f"a full charge now gives about {a.full_range_km:.0f} km "
                   f"(about {a.full_range_km / (a.soh_pct / 100):.0f} km when new).")
    soh = a.soh_pct
    if soh is not None and soh <= EV_EOL_SOH_PCT:
        out.append("Maintenance: the battery is at or below 80 % SoH (end of life for traction use). "
                   "Confirm with a capacity test and plan replacement or second-life use.")
    elif soh is not None and soh <= SOH_WATCH_PCT:
        out.append("Maintenance: SoH is within 5 points of end of life. Schedule a capacity test and "
                   "a battery-management check, and repeat the assessment every 3 months.")
    else:
        out.append("Maintenance: no action needed beyond the routine yearly battery check.")
    if usage.get("fast_charge_ratio") is not None and usage["fast_charge_ratio"] > 0.5:
        out.append(f"Battery care: {usage['fast_charge_ratio']:.0%} of charging is DC fast charging; "
                   "using AC charging where possible reduces heat stress.")
    if usage.get("avg_soc") is not None and usage["avg_soc"] > 80:
        out.append(f"Battery care: the battery is kept at {usage['avg_soc']:.0f} % charge on average; "
                   "keeping it between about 20 and 80 % for daily use slows ageing.")
    if usage.get("hot"):
        out.append("Battery care: high temperatures were recorded; parking in shade and avoiding fast "
                   "charging right after long drives reduce thermal stress.")
    return out



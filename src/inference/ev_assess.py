def load_quick_models() -> dict:
    out = {}
    for key in ("quick_soh", "quick_rul"):
        path = MODELS_DIR / f"ev_{key}.joblib"
        if not path.exists():
            raise FileNotFoundError(str(path))
        out[key] = joblib.load(path)
    return out


def model_error(task: str) -> float:
    meta = json.loads((MODELS_DIR / f"ev_{task}.json").read_text())
    return float(meta["test_scores"]["MAE"])


def model_meta(task: str) -> dict:
    return json.loads((MODELS_DIR / f"ev_{task}.json").read_text())


def interval(meta: dict, pred: float | None, *, rul: bool, unknown: bool = False) -> tuple[float, float] | None:
    """90 % interval around `pred` from the model's calibration (None if not calibrated)."""
    iv = meta.get("interval_categories_unknown") if unknown else None
    iv = iv or meta.get("interval")
    if iv is None or pred is None:
        return None
    lo, hi = apply_interval(iv, [pred], (0.0, None) if rul else (0.0, 100.0))
    return float(lo[0]), float(hi[0])


def load_masker() -> OutlierMasker | None:
    path = MODELS_DIR / "ev_outlier_masker.json"
    return OutlierMasker.from_dict(json.loads(path.read_text())) if path.exists() else None


def quick_features(age_days, efc, chemistry=None, climate=None) -> pd.DataFrame:
    age = np.atleast_1d(np.asarray(age_days, float))
    efc = np.atleast_1d(np.asarray(efc, float))
    n = len(age)
    norm = lambda v: np.nan if v in (None, "Unknown", "") or (isinstance(v, float) and np.isnan(v)) else v
    chem = [norm(c) for c in (chemistry if isinstance(chemistry, (list, np.ndarray, pd.Series)) else [chemistry] * n)]
    clim = [norm(c) for c in (climate if isinstance(climate, (list, np.ndarray, pd.Series)) else [climate] * n)]
    return pd.DataFrame({"chemistry": pd.Series(chem, dtype=object), "climate_zone": pd.Series(clim, dtype=object),
                         "battery_age_days": age, "efc": efc, "efc_per_day": efc / np.clip(age, 1, None)})


def predict_quick(models: dict, X: pd.DataFrame) -> tuple[np.ndarray, np.ndarray]:
    soh = np.clip(models["quick_soh"]["pipeline"].predict(X), 0, 100)
    rul = np.clip(models["quick_rul"]["pipeline"].predict(X), 0, None)
    rul = np.where(soh <= EV_EOL_SOH_PCT, 0.0, rul)
    return soh, rul


